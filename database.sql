-- Product fields and image metadata commit together; files upload before this call.
create function public.save_product(p_id bigint, p_product jsonb, p_images jsonb) returns bigint
language plpgsql security definer set search_path = '' as $$
declare result_id bigint;
begin
  if not public.is_admin() then raise exception 'Admin huquqi kerak.' using errcode='42501'; end if;
  if jsonb_typeof(p_images) is distinct from 'array' then raise exception 'Rasm ro‘yxati noto‘g‘ri.'; end if;
  if jsonb_array_length(p_images) > 12 then raise exception 'Eng ko‘pi 12 ta rasm.'; end if;
  if p_id is null then
    insert into public.products(name,category_id,description,cash_price,discount_price,stock_quantity,installment_enabled,is_active)
    values(p_product->>'name',p_product->>'category_id',coalesce(p_product->>'description',''),(p_product->>'cash_price')::bigint,nullif(p_product->>'discount_price','')::bigint,(p_product->>'stock_quantity')::integer,(p_product->>'installment_enabled')::boolean,(p_product->>'is_active')::boolean) returning id into result_id;
  else
    perform 1 from public.products where id=p_id and updated_at=(p_product->>'expected_updated_at')::timestamptz for update;
    if not found then raise exception 'Mahsulot yangilangan. Ma’lumotlarni qayta oching.'; end if;
    update public.products set name=p_product->>'name',category_id=p_product->>'category_id',description=coalesce(p_product->>'description',''),cash_price=(p_product->>'cash_price')::bigint,discount_price=nullif(p_product->>'discount_price','')::bigint,stock_quantity=(p_product->>'stock_quantity')::integer,installment_enabled=(p_product->>'installment_enabled')::boolean,is_active=(p_product->>'is_active')::boolean where id=p_id returning id into result_id;
    if result_id is null then raise exception 'Mahsulot topilmadi.'; end if;
  end if;
  delete from public.product_images where product_id=result_id;
  insert into public.product_images(product_id,image_url,sort_order)
  select result_id, value #>> '{}', (ordinality-1)::integer from jsonb_array_elements(p_images) with ordinality;
  return result_id;
end;
$$;
revoke all on function public.save_product(bigint,jsonb,jsonb) from public;
grant execute on function public.save_product(bigint,jsonb,jsonb) to authenticated;

-- Pricing authority stays on the server. No price/total from the browser is trusted.
create function private.installment_total(p_cash bigint, p_months integer) returns bigint
language plpgsql immutable set search_path = '' as $$
declare factor numeric;
begin
  factor := case p_months when 3 then 1.1545 when 6 then 1.30 when 9 then 1.40 when 12 then 1.45 else null end;
  if factor is null then raise exception 'To‘lov muddati noto‘g‘ri.'; end if;
  return round(p_cash * factor)::bigint;
end;
$$;
create table private.checkout_attempts(ip_hash text not null, created_at timestamptz not null default now());
create index on private.checkout_attempts(ip_hash,created_at);
create function public.checkout_rate_limit(p_ip_hash text) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if p_ip_hash is null or length(p_ip_hash)<>64 then return false; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_ip_hash,0));
  delete from private.checkout_attempts where created_at < now()-interval '1 hour';
  if (select count(*) from private.checkout_attempts where ip_hash=p_ip_hash and created_at>now()-interval '10 minutes')>=10 then return false; end if;
  insert into private.checkout_attempts(ip_hash) values(p_ip_hash);
  return true;
end;
$$;
